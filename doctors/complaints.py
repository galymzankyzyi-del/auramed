def get_complaints_for_doctor(specialization):
    """
    Возвращает варианты жалоб по специальности врача.
    """

    name = (specialization or "").strip().casefold()

    # Сначала ищем точное совпадение.
    if name in COMPLAINTS:
        return COMPLAINTS[name]

    # Затем допускаем составные названия
    # например "Врач-дерматолог".
    for key, complaints in COMPLAINTS.items():
        if key in name:
            return complaints

    # Список для неизвестной специальности.
    return DEFAULT_COMPLAINTS
